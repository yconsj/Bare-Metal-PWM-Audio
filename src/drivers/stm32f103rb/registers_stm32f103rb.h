#ifndef REGISTERS_STM32F103RB_H
#define REGISTERS_STM32F103RB_H
#include <stdint.h>

#define STM32_PERIPH_BASE         (0x40000000UL)
#define STM32_APB1_PERIPH_BASE    (STM32_PERIPH_BASE)
#define STM32_APB2_PERIPH_BASE    (STM32_APB1_PERIPH_BASE + 0x10000)
#define STM32_AHB_PERIPH_BASE     (STM32_APB2_PERIPH_BASE + 0x8000)

#define STM32_RCC_BASE            (STM32_AHB_PERIPH_BASE + 0x9000)
#define STM32_RCC                 ((STM32_rcc_t *) STM32_RCC_BASE)



/* RCC macros*/
#define STM32_RCC_APB2ENR_IOPAEN  (1U << 2)
#define STM32_RCC_APB2ENR_IOPBEN  (STM32_RCC_APB2ENR_IOPAEN << 1)
#define STM32_RCC_APB2ENR_IOPCEN  (STM32_RCC_APB2ENR_IOPBEN << 1)
#define STM32_RCC_APB2ENR_IOPDEN  (STM32_RCC_APB2ENR_IOPCEN << 1)




#define STM32_GPIO_BASE           (STM32_APB2_PERIPH_BASE + 0x800)
#define STM32_GPIOA_BASE          (STM32_GPIO_BASE)
#define STM32_GPIOB_BASE          (STM32_GPIOA_BASE + 0x400)
#define STM32_GPIOC_BASE          (STM32_GPIOB_BASE + 0x400)
#define STM32_GPIOD_BASE          (STM32_GPIOC_BASE + 0x400)
#define STM32_GPIOE_BASE          (STM32_GPIOD_BASE + 0x400)
#define STM32_GPIOF_BASE          (STM32_GPIOE_BASE + 0x400)
#define STM32_GPIOG_BASE          (STM32_GPIOF_BASE + 0x400)
#define STM32_GPIOA               ((STM32_gpio_t*) STM32_GPIOA_BASE)
#define STM32_GPIOB               ((STM32_gpio_t*) STM32_GPIOB_BASE)
#define STM32_GPIOC               ((STM32_gpio_t*) STM32_GPIOC_BASE)
#define STM32_GPIOD               ((STM32_gpio_t*) STM32_GPIOD_BASE)



#endif 
